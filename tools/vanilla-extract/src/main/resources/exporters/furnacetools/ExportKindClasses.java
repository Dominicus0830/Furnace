package furnacetools;

import java.io.FileOutputStream;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;

/**
 * T-231: 블록·아이템 종류 → 바닐라 클래스 표(레지스트리 순서). shim 생성기가 이 클래스들(과 상위 사슬)의 선언을 만들고,
 * 호환 모듈이 블록·아이템 객체를 그 클래스로 만든다({@code Blocks.WHEAT instanceof CropBlock}). 줄마다:
 *   B <블록> <클래스 이진 이름>
 *   I <아이템> <클래스 이진 이름>
 *   E <엔티티 종류> <클래스 이진 이름>(T-232 — {@code EntityType} 상수 필드의 형식 인자. 구체 클래스이고 (EntityType, Level) 생성자가 있어야 한다.
 *     레벨 없이 만들어지는 종류는 만들어 본 클래스와 같은지도 본다. 플레이어(공장이 없음)는 뺀다 — 호환 모듈에서 늘 ServerPlayer 다)
 * 익명·지역 클래스는 없어야 한다(있으면 실패 — 이름 붙은 상위로 바꿀지 정해야 하므로). 인자: <출력>.
 */
public class ExportKindClasses {
    public static void main(String[] a) throws Exception {
        Vanilla.boot();
        Registry<Block> blocks = BuiltInRegistries.BLOCK;
        Registry<Item> items = BuiltInRegistries.ITEM;
        try (PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(a[0]), "UTF-8"))) {
            w.println("# Generated by " + Vanilla.generator("ExportKindClasses") + " - do not edit. B <block> <class> / I <item> <class> / E <entity type> <class> (registry order)");
            for (Block b : blocks) w.println("B " + blocks.getKey(b) + " " + name(b.getClass()));
            for (Item i : items) w.println("I " + items.getKey(i) + " " + name(i.getClass()));
            int made = 0;
            for (EntityType<?> t : BuiltInRegistries.ENTITY_TYPE) {
                if (t == EntityType.PLAYER) continue;
                Class<?> c = entityClass(t);
                if (Modifier.isAbstract(c.getModifiers())) throw new IllegalStateException("abstract entity class " + c + " for " + t);
                c.getDeclaredConstructor(EntityType.class, net.minecraft.world.level.Level.class);   // 없으면 NoSuchMethodException
                Object e;
                try {
                    e = factory(t).create(t, null);
                } catch (Throwable needsLevel) {
                    e = null;   // 레벨이 있어야 만들어지는 종류 — 형식 인자만 쓴다
                }
                if (e != null) {
                    if (e.getClass() != c) throw new IllegalStateException(t + ": type argument " + c + " but the factory made " + e.getClass());
                    made++;
                }
                w.println("E " + BuiltInRegistries.ENTITY_TYPE.getKey(t) + " " + name(c));
            }
            System.out.println("entity kinds checked by creating them without a level: " + made);
        }
        System.out.println("done");
    }

    /** 종류의 공장(바닐라 private 필드 — create(Level) 은 레벨의 기능 플래그부터 읽어 레벨 없이 못 부른다). */
    @SuppressWarnings({"unchecked", "rawtypes"})
    static EntityType.EntityFactory factory(EntityType<?> t) throws IllegalAccessException {
        for (Field f : EntityType.class.getDeclaredFields()) {
            if (f.getType() != EntityType.EntityFactory.class || Modifier.isStatic(f.getModifiers())) continue;
            f.setAccessible(true);
            return (EntityType.EntityFactory) f.get(t);
        }
        throw new IllegalStateException("no factory field on EntityType");
    }

    /** 그 종류 상수 필드(EntityType<클래스>)의 형식 인자. */
    static Class<?> entityClass(EntityType<?> t) throws IllegalAccessException {
        for (Field f : EntityType.class.getDeclaredFields()) {
            if (!Modifier.isStatic(f.getModifiers()) || f.getType() != EntityType.class || f.get(null) != t) continue;
            if (f.getGenericType() instanceof ParameterizedType p && p.getActualTypeArguments()[0] instanceof Class<?> c) return c;
            throw new IllegalStateException("no class type argument on " + f);
        }
        throw new IllegalStateException("no EntityType constant for " + t);
    }

    static String name(Class<?> c) {
        if (c.isAnonymousClass() || c.isLocalClass() || c.isSynthetic()) throw new IllegalStateException("unnamed kind class: " + c);
        return c.getName();
    }
}

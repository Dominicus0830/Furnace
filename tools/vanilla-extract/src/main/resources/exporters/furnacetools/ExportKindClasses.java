package furnacetools;

import java.io.FileOutputStream;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.world.item.Item;
import net.minecraft.world.level.block.Block;

/**
 * T-231: 블록·아이템 종류 → 바닐라 클래스 표(레지스트리 순서). shim 생성기가 이 클래스들(과 상위 사슬)의 선언을 만들고,
 * 호환 모듈이 블록·아이템 객체를 그 클래스로 만든다({@code Blocks.WHEAT instanceof CropBlock}). 줄마다:
 *   B <블록> <클래스 이진 이름>
 *   I <아이템> <클래스 이진 이름>
 * 익명·지역 클래스는 없어야 한다(있으면 실패 — 이름 붙은 상위로 바꿀지 정해야 하므로). 인자: <출력>.
 */
public class ExportKindClasses {
    public static void main(String[] a) throws Exception {
        Vanilla.boot();
        Registry<Block> blocks = BuiltInRegistries.BLOCK;
        Registry<Item> items = BuiltInRegistries.ITEM;
        try (PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(a[0]), "UTF-8"))) {
            w.println("# Generated by " + Vanilla.generator("ExportKindClasses") + " - do not edit. B <block> <class> / I <item> <class> (registry order)");
            for (Block b : blocks) w.println("B " + blocks.getKey(b) + " " + name(b.getClass()));
            for (Item i : items) w.println("I " + items.getKey(i) + " " + name(i.getClass()));
        }
        System.out.println("done");
    }

    static String name(Class<?> c) {
        if (c.isAnonymousClass() || c.isLocalClass() || c.isSynthetic()) throw new IllegalStateException("unnamed kind class: " + c);
        return c.getName();
    }
}

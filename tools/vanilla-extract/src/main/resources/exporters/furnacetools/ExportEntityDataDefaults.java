/**
 * 엔티티 데이터 D1b: 종류마다 칸의 처음 값 두 개(정의 값 = DataItem.initialValue, 생성 뒤 값 = DataItem.value)를 뽑는다. 인자: <출력>.
 * <p>줄: {@code <종류> <칸 번호> <정의 값> <생성 뒤 값>} — 값은 바닐라 칸 코덱으로 쓴 바이트(16진). 데이터 팩 레지스트리 홀더
 * (늑대·그림 변형)는 번호가 레지스트리 차례에 달려 있으므로 {@code @<키>} 로 쓴다. 생성 뒤 값이 정의 값과 같으면 {@code =}, 엔티티 난수 때문에 만들 때마다 다른 바이트는 {@code ??}(길이까지 다르면 값 전체 {@code ~}).
 * <p>서버 없이 만들어야 하므로 레벨은 생성자를 거치지 않은 ServerLevel 에 난수·레지스트리·프로파일러만 채운 것이다.
 * 엔티티 생성자가 그 밖의 레벨 상태를 읽으면 실패로 기록하고 멈춘다(빠지는 종류가 있으면 표를 쓰지 않는다).
 * 플레이어는 서버 없이 만들 수 없어 뺀다(엔티티 데이터 설계 3.2 — 이번 범위 밖).
 */
public class ExportEntityDataDefaults {
    static final String GEN = "tools/vanilla-extract/src/main/resources/exporters/furnacetools/ExportEntityDataDefaults.java";
    static final int TRIES = 16;
    static final List<String> BY_KEY = List.of("wolf_variant", "painting_variant");

    public static void main(String[] a) throws Exception {
        Vanilla.boot();
        RegistryAccess access = registryAccess();
        Level level = fakeLevel(access);
        Map<EntityDataSerializer<?>, String> names = serializerNames();
        TreeMap<String, List<String>> rows = new TreeMap<>();
        List<String> failed = new ArrayList<>();
        for (EntityType<?> t : BuiltInRegistries.ENTITY_TYPE) {
            String kind = BuiltInRegistries.ENTITY_TYPE.getKey(t).toString();
            if (t == EntityType.PLAYER) continue;
            // 엔티티 난수(RandomSource.create(), 씨앗 없음)를 쓰는 생성자(좀비 주민 직업 등)는 생성 뒤 값이 매번 다르다: 여러 번 만들어 다른 바이트는 ??
            List<List<String[]>> runs = new ArrayList<>();
            try {
                for (int n = 0; n < TRIES; n++) runs.add(slots(create(t, level), names, access));
            } catch (Throwable x) {
                failed.add(kind + ": " + x);
                continue;
            }
            List<String> out = new ArrayList<>();
            List<String[]> first = runs.get(0);
            for (int id = 0; id < first.size(); id++) {
                String defined = first.get(id)[0], now = first.get(id)[1];
                for (List<String[]> r : runs) {
                    if (!r.get(id)[0].equals(defined)) throw new IllegalStateException(kind + " slot " + id + ": defined value differs between instances");
                    now = merge(now, r.get(id)[1]);
                }
                out.add(kind + " " + id + " " + defined + " " + (now.equals(defined) ? "=" : now));
            }
            rows.put(kind, out);
        }
        if (!failed.isEmpty()) {
            failed.forEach(f -> System.err.println("[entity-data-defaults] " + f));
            throw new IllegalStateException(failed.size() + " entity types could not be created; table not written");
        }
        try (PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(a[0]), "UTF-8"))) {
            w.println("# Generated by " + GEN + " - do not edit. <entity type> <data slot> <defined value> <constructed value, = if same, ?? for bytes and ~ for values that differ between instances> (codec bytes hex, @key for data-pack registry holders)");
            rows.values().forEach(l -> l.forEach(w::println));
        }
        System.out.println("done " + rows.size());
    }

    /** 두 생성의 값을 합친다: 같은 길이면 다른 바이트만 ??(좀비 주민 직업 — 종류·레벨은 견준다), 길이가 다르면 ~. */
    static String merge(String a, String b) {
        if (a.equals(b)) return a;
        if (a.equals("~") || a.length() != b.length()) return "~";
        StringBuilder m = new StringBuilder(a.length());
        for (int i = 0; i < a.length(); i += 2) m.append(a.regionMatches(i, b, i, 2) ? a.substring(i, i + 2) : "??");
        return m.toString();
    }

    /** 칸마다 {정의 값, 생성 뒤 값}, 칸 번호 순. */
    static List<String[]> slots(Entity e, Map<EntityDataSerializer<?>, String> names, RegistryAccess access) throws Exception {
        List<String[]> out = new ArrayList<>();
        for (Object item : itemsById(e.getEntityData())) {
            var acc = (EntityDataAccessor<?>) field(item, "accessor");
            if (acc.id() != out.size()) throw new IllegalStateException("data slots out of order at " + acc.id());
            EntityDataSerializer<?> ser = acc.serializer();
            String serName = names.get(ser).toLowerCase();
            out.add(new String[] {encode(serName, ser, field(item, "initialValue"), access), encode(serName, ser, field(item, "value"), access)});
        }
        return out;
    }

    @SuppressWarnings("unchecked")
    static Entity create(EntityType<?> t, Level level) throws Exception {
        // EntityType.create 는 레벨의 기능 깃발(서버 설정)을 보므로 공장을 바로 부른다
        Field ff = EntityType.class.getDeclaredField("factory");
        ff.setAccessible(true);
        @SuppressWarnings("unchecked")
        var factory = (EntityType.EntityFactory<Entity>) ff.get(t);
        Entity e = factory.create((EntityType<Entity>) t, level);
        if (e != null) return e;
        if (t == EntityType.FISHING_BOBBER) {   // 공장이 없는 종류: (EntityType, Level) 생성자
            Constructor<?> c = net.minecraft.world.entity.projectile.FishingHook.class.getDeclaredConstructor(EntityType.class, Level.class);
            c.setAccessible(true);
            return (Entity) c.newInstance(t, level);
        }
        throw new IllegalStateException("EntityType.create returned null");
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    static String encode(String serName, EntityDataSerializer ser, Object v, RegistryAccess access) {
        if (BY_KEY.contains(serName)) {
            return "@" + ((Holder<?>) v).unwrapKey().orElseThrow(() -> new IllegalStateException("direct holder in " + serName)).location();
        }
        ByteBuf raw = Unpooled.buffer();
        ser.codec().encode(new RegistryFriendlyByteBuf(raw, access), v);
        byte[] b = new byte[raw.readableBytes()];
        raw.readBytes(b);
        StringBuilder s = new StringBuilder(b.length * 2 + 1);
        for (byte x : b) s.append(String.format("%02x", x));
        return s.length() == 0 ? "-" : s.toString();
    }

    /** EntityDataSerializers 의 정적 직렬화기 상수 이름(도구마다 따로 컴파일되므로 ExportEntityData 와 같은 코드를 둔다). */
    static Map<EntityDataSerializer<?>, String> serializerNames() throws Exception {
        Map<EntityDataSerializer<?>, String> m = new java.util.IdentityHashMap<>();
        for (Field f : EntityDataSerializers.class.getDeclaredFields()) {
            if (!java.lang.reflect.Modifier.isStatic(f.getModifiers()) || !EntityDataSerializer.class.isAssignableFrom(f.getType())) continue;
            f.setAccessible(true);
            m.put((EntityDataSerializer<?>) f.get(null), f.getName());
        }
        return m;
    }

    static Object[] itemsById(SynchedEntityData d) throws Exception {
        Field f = SynchedEntityData.class.getDeclaredField("itemsById");
        f.setAccessible(true);
        return (Object[]) f.get(d);
    }

    static Object field(Object o, String name) throws Exception {
        for (Class<?> c = o.getClass(); c != null; c = c.getSuperclass()) {
            try {
                Field f = c.getDeclaredField(name);
                f.setAccessible(true);
                return f.get(o);
            } catch (NoSuchFieldException ignored) {
                // 위 부류에서 찾는다
            }
        }
        throw new NoSuchFieldException(o.getClass().getName() + "." + name);
    }

    /** 내장 레지스트리 + 바닐라 부트스트랩이 정의한 데이터 팩 레지스트리(늑대·그림 변형, 피해 종류 등). 데이터 팩 레지스트리는 키 이름순으로 등록한다. */
    @SuppressWarnings({"unchecked", "rawtypes"})
    static RegistryAccess registryAccess() {
        var lookup = VanillaRegistries.createLookup();
        Map<ResourceKey<?>, Registry<?>> data = new HashMap<>();
        lookup.listRegistries().forEach(k -> {
            ResourceKey key = (ResourceKey) k;
            if (BuiltInRegistries.REGISTRY.containsKey(key.location())) return;   // 내장 레지스트리는 그대로(번호가 등록 차례)
            net.minecraft.core.HolderLookup.RegistryLookup rl = lookup.lookupOrThrow(key);
            MappedRegistry r = new MappedRegistry(key, com.mojang.serialization.Lifecycle.stable());
            // 진짜 서버는 데이터 팩 파일을 이름순(TreeMap)으로 읽어 등록한다 — getAny()(그림 처음 값)가 이 차례를 따른다
            ((java.util.stream.Stream<?>) rl.listElements())
                    .sorted(java.util.Comparator.comparing(ref -> ((Holder.Reference<?>) ref).key().location().toString())).forEach(ref -> Registry.register(r, ((Holder.Reference) ref).key(), ((Holder.Reference) ref).value()));
            data.put(key, r.freeze());
        });
        List<Registry<?>> all = new ArrayList<>(data.values());
        for (Registry<?> r : BuiltInRegistries.REGISTRY) if (!data.containsKey(r.key())) all.add(r);
        return new RegistryAccess.ImmutableRegistryAccess(all).freeze();
    }

    /** 생성자를 거치지 않은 ServerLevel: 엔티티 생성자가 읽는 난수·레지스트리·프로파일러·피해 원천만 채운다. */
    static Level fakeLevel(RegistryAccess access) throws Exception {
        Field uf = sun.misc.Unsafe.class.getDeclaredField("theUnsafe");
        uf.setAccessible(true);
        sun.misc.Unsafe u = (sun.misc.Unsafe) uf.get(null);
        Level level = (Level) u.allocateInstance(ServerLevel.class);
        put(u, level, Level.class, "random", RandomSource.create(0L));
        put(u, level, Level.class, "threadSafeRandom", RandomSource.createThreadSafe());
        put(u, level, Level.class, "registryAccess", access);
        put(u, level, Level.class, "profiler", (java.util.function.Supplier<?>) () -> InactiveProfiler.INSTANCE);
        put(u, level, Level.class, "damageSources", new DamageSources(access));
        // 마을 주민 뇌는 시각을, 위더 보스바는 표시 이름(팀 → 점수판)을 읽는다: 시각 0 인 세계 정보, 빈 점수판을 가진 서버
        put(u, level, Level.class, "levelData", java.lang.reflect.Proxy.newProxyInstance(ExportEntityDataDefaults.class.getClassLoader(),
                new Class<?>[] {net.minecraft.world.level.storage.WritableLevelData.class}, (proxy, m, args) -> zero(m.getReturnType())));
        Object server = u.allocateInstance(net.minecraft.server.dedicated.DedicatedServer.class);
        put(u, server, net.minecraft.server.MinecraftServer.class, "scoreboard",
                new net.minecraft.server.ServerScoreboard((net.minecraft.server.MinecraftServer) server));
        put(u, level, ServerLevel.class, "server", server);
        return level;
    }

    static Object zero(Class<?> t) {
        if (t == long.class) return 0L;
        if (t == int.class) return 0;
        if (t == boolean.class) return false;
        if (t == float.class) return 0F;
        if (t == double.class) return 0D;
        return null;
    }

    static void put(sun.misc.Unsafe u, Object o, Class<?> owner, String name, Object v) throws Exception {
        Field f = owner.getDeclaredField(name);
        u.putObject(o, u.objectFieldOffset(f), v);
    }
}

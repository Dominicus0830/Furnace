package furnacetools;

import java.io.FileOutputStream;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.network.syncher.EntityDataAccessor;
import net.minecraft.network.syncher.EntityDataSerializer;
import net.minecraft.network.syncher.EntityDataSerializers;
import net.minecraft.world.entity.EntityType;

/**
 * V-04: 엔티티 메타데이터 표 셋. 인자: <배치 출력> <주인 부류 출력> <번호 출력>.
 * <ul>
 * <li>배치: 줄마다 {@code <엔티티 종류> <값 종류 소문자…>} — 칸 번호 순, 종류 이름순(플레이어 포함).</li>
 * <li>주인 부류: 줄마다 {@code <엔티티 종류> <클래스 단순 이름…>} — Entity 에서 그 종류의 클래스까지(위 → 아래, 칸을 선언한 부류만), 종류 이름순.</li>
 * <li>번호: {@code S <번호> <직렬화기 상수>}(직렬화기 등록 순서) 와
 *     {@code A <클래스 이진 이름> <상수 이름> <칸 번호> <직렬화기 상수>}(클래스가 선언한 EntityDataAccessor 상수, 클래스 이름·칸 번호 순).</li>
 * </ul>
 * 칸은 실제 엔티티를 만들지 않고 클래스 계층의 정적 EntityDataAccessor 상수로 읽는다(레벨 없이 못 만드는 종류가 있다).
 */
public class ExportEntityData {
    public static void main(String[] a) throws Exception {
        Vanilla.boot();
        Map<EntityDataSerializer<?>, String> names = serializerNames();
        List<EntityDataSerializer<?>> ordered = new ArrayList<>();
        for (int i = 0; ; i++) {
            EntityDataSerializer<?> s = EntityDataSerializers.getSerializer(i);
            if (s == null) break;
            ordered.add(s);
        }
        TreeMap<String, List<Object[]>> declared = new TreeMap<>();   // 클래스 이진 이름 → {상수 이름, 번호, 직렬화기 이름}
        try (PrintWriter layouts = open(a[0]); PrintWriter owners = open(a[1])) {
            layouts.println("# Generated by " + Vanilla.generator("ExportEntityData") + " - do not edit. <entity type> <value kind per data slot, slot order>");
            owners.println("# Generated by " + Vanilla.generator("ExportEntityData") + " - do not edit. <entity type> <vanilla class simple names, Entity first>");
            TreeMap<String, String> layoutRows = new TreeMap<>(), ownerRows = new TreeMap<>(PLAYER_LAST);
            for (EntityType<?> t : BuiltInRegistries.ENTITY_TYPE) {
                Class<?> c = entityClass(t);
                List<Class<?>> chain = new ArrayList<>();
                for (Class<?> k = c; k != null && k != Object.class; k = k.getSuperclass()) chain.add(0, k);
                TreeMap<Integer, String> slots = new TreeMap<>();
                StringBuilder own = new StringBuilder();
                for (Class<?> k : chain) {
                    boolean any = false;
                    for (Field f : k.getDeclaredFields()) {
                        if (!Modifier.isStatic(f.getModifiers()) || f.getType() != EntityDataAccessor.class) continue;
                        f.setAccessible(true);
                        EntityDataAccessor<?> acc = (EntityDataAccessor<?>) f.get(null);
                        int id = id(acc);
                        String ser = names.get(serializer(acc));
                        if (ser == null) throw new IllegalStateException("unknown serializer on " + k.getName() + "." + f.getName());
                        String prev = slots.put(id, ser.toLowerCase());
                        if (prev != null) throw new IllegalStateException(c.getName() + ": data slot " + id + " defined twice (" + f.getName() + ")");
                        any = true;
                        List<Object[]> list = declared.computeIfAbsent(k.getName(), x -> new ArrayList<>());
                        if (list.stream().noneMatch(o -> o[0].equals(f.getName()))) list.add(new Object[] {f.getName(), id, ser});   // 같은 부류는 종류마다 다시 만난다
                    }
                    if (any) own.append(' ').append(k.getSimpleName());   // 칸을 선언한 부류만
                }
                int expect = 0;
                StringBuilder row = new StringBuilder(BuiltInRegistries.ENTITY_TYPE.getKey(t).toString());
                for (Map.Entry<Integer, String> e : slots.entrySet()) {
                    if (e.getKey() != expect++) throw new IllegalStateException(c.getName() + ": data slots are not contiguous at " + e.getKey());
                    row.append(' ').append(e.getValue());
                }
                layoutRows.put(BuiltInRegistries.ENTITY_TYPE.getKey(t).toString(), row.toString());
                ownerRows.put(BuiltInRegistries.ENTITY_TYPE.getKey(t).toString(), BuiltInRegistries.ENTITY_TYPE.getKey(t) + own.toString());
            }
            layoutRows.values().forEach(layouts::println);
            ownerRows.values().forEach(owners::println);
        }
        try (PrintWriter w = open(a[2])) {
            w.println("# Generated by " + Vanilla.generator("ExportEntityData") + " - do not edit. S <serializer id> <EntityDataSerializers constant> / A <class> <constant> <data slot> <serializer constant>");
            for (int i = 0; i < ordered.size(); i++) w.println("S " + i + " " + names.get(ordered.get(i)));
            for (Map.Entry<String, List<Object[]>> e : declared.entrySet()) {
                e.getValue().sort((x, y) -> Integer.compare((Integer) x[1], (Integer) y[1]));
                for (Object[] f : e.getValue()) w.println("A " + e.getKey() + " " + f[0] + " " + f[1] + " " + f[2]);
            }
        }
        System.out.println("done");
    }

    /** 그 종류 상수 필드(EntityType<클래스>)의 형식 인자(도구마다 따로 컴파일되므로 ExportKindClasses 와 같은 코드를 둔다). */
    static Class<?> entityClass(EntityType<?> t) throws IllegalAccessException {
        for (Field f : EntityType.class.getDeclaredFields()) {
            if (!Modifier.isStatic(f.getModifiers()) || f.getType() != EntityType.class || f.get(null) != t) continue;
            if (f.getGenericType() instanceof java.lang.reflect.ParameterizedType p && p.getActualTypeArguments()[0] instanceof Class<?> c) return c;
            throw new IllegalStateException("no class type argument on " + f);
        }
        throw new IllegalStateException("no EntityType constant for " + t);
    }

    /** 주인 부류 표는 플레이어 줄이 맨 끝이다(저장소에 있던 순서 그대로). 나머지는 이름순. */
    static final java.util.Comparator<String> PLAYER_LAST = java.util.Comparator.<String, Boolean>comparing(k -> k.equals("minecraft:player")).thenComparing(java.util.Comparator.naturalOrder());

    static PrintWriter open(String path) throws Exception {
        return new PrintWriter(new OutputStreamWriter(new FileOutputStream(path), "UTF-8"));
    }

    /** EntityDataSerializers 의 정적 직렬화기 상수 이름(같은 객체가 둘이면 실패). */
    static Map<EntityDataSerializer<?>, String> serializerNames() throws Exception {
        Map<EntityDataSerializer<?>, String> m = new IdentityHashMap<>();
        for (Field f : EntityDataSerializers.class.getDeclaredFields()) {
            if (!Modifier.isStatic(f.getModifiers()) || !EntityDataSerializer.class.isAssignableFrom(f.getType())) continue;
            f.setAccessible(true);
            if (m.put((EntityDataSerializer<?>) f.get(null), f.getName()) != null) throw new IllegalStateException("serializer constant twice: " + f.getName());
        }
        return m;
    }

    /** 칸 번호: record 면 id(), 아니면 int 를 돌려주는 인자 없는 공개 메서드 하나. */
    static int id(EntityDataAccessor<?> acc) throws Exception {
        Method found = null;
        for (Method m : EntityDataAccessor.class.getMethods()) {
            if (m.getParameterCount() == 0 && m.getReturnType() == int.class && !m.getName().equals("hashCode")) {
                if (found != null) throw new IllegalStateException("two int accessors on EntityDataAccessor");
                found = m;
            }
        }
        if (found == null) throw new IllegalStateException("no int accessor on EntityDataAccessor");
        return (Integer) found.invoke(acc);
    }

    static EntityDataSerializer<?> serializer(EntityDataAccessor<?> acc) throws Exception {
        for (Method m : EntityDataAccessor.class.getMethods()) {
            if (m.getParameterCount() == 0 && EntityDataSerializer.class.isAssignableFrom(m.getReturnType())) return (EntityDataSerializer<?>) m.invoke(acc);
        }
        throw new IllegalStateException("no serializer accessor on EntityDataAccessor");
    }
}
